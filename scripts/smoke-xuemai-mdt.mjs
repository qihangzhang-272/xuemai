import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const base=process.env.XUEMAI_TEST_URL||'http://127.0.0.1:3016';
assert(['127.0.0.1','localhost'].includes(new URL(base).hostname));
const identifier=process.env.MDT_TEST_IDENTIFIER;
const password=process.env.MDT_TEST_PASSWORD;
assert(identifier&&password,'通过临时环境变量提供 MDT 教师账号');
let cookie='';
async function call(path,body){const response=await fetch(`${base}/api/xuemai/${path}`,{method:body?'POST':'GET',headers:{Cookie:cookie,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});const data=await response.json();assert.equal(response.status,200,JSON.stringify(data));return{data,response};}
const auth=await call('auth',{mode:'mdt',identifier,password});
cookie=auth.response.headers.getSetCookie().map(c=>c.split(';')[0]).join('; ');
const before=(await call('mdt')).data;
assert(before.classes.length);
const klass=before.classes.find(c=>c._count.students>0)||before.classes[0];
const ranking=(await call(`mdt?classId=${klass.classId}`)).data;
const first=(await call('mdt',{action:'import',classId:String(klass.classId)})).data;
const state1=(await call('state')).data;
await call('mdt',{action:'import',classId:String(klass.classId)});
const state2=(await call('state')).data;
assert.equal(state1.contacts.length,state2.contacts.length);
assert.equal(state2.records.length,0);
const after=(await call('mdt')).data;
assert.deepEqual(before.classes,after.classes);
const report={ok:true,time:new Date().toISOString(),teacherLogin:true,classesRead:before.classes.length,studentsRead:ranking.students.length,studentsImported:first.imported,repeatedImportKeepsCount:true,noLocalRecordsInvented:true,remoteClassesUnchanged:true};
await writeFile('output/mdt-smoke.json',JSON.stringify(report,null,2));console.log(report);
